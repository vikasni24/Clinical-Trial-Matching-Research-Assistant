"""The structured, deterministic result of evaluating one PatientProfile
against one ClinicalTrial. Every field here is derived directly from values
already present in the profile/trial — nothing is inferred or generated by
an LLM.
"""

from datetime import datetime
from typing import Any, Optional

from pydantic import BaseModel


class CriterionEvaluationOut(BaseModel):
    criterion: str
    category: str  # "demographics" | "condition" | "medication" | "allergy" | "observation"
    requirement: str  # "inclusion" | "exclusion"
    result: str  # "PASS" | "FAIL" | "UNKNOWN"
    patient_value: Optional[Any] = None
    required_value: Optional[str] = None
    reason: str


class MatchResultOut(BaseModel):
    patient_id: str
    trial_id: str
    overall_status: Optional[str] = None  # the trial's own recruitment status at evaluation time
    eligibility_status: str  # "ELIGIBLE" | "INELIGIBLE" | "UNKNOWN"
    match_score: float  # matched_criteria / total_criteria evaluated, 0.0-1.0 — see EligibilityMatcher docstring
    matched_criteria: list[CriterionEvaluationOut] = []
    failed_criteria: list[CriterionEvaluationOut] = []
    unknown_criteria: list[CriterionEvaluationOut] = []
    explanation: str
    evaluated_at: Optional[datetime] = None


class MatchListOut(BaseModel):
    patient_id: str
    total_trials_evaluated: int
    matches: list[MatchResultOut] = []
